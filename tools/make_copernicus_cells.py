"""Write copernicus_cells.py from Copernicus's own lists of its tiles.

    python tools/make_copernicus_cells.py <30 m tileList.txt> <90 m tileList.txt>

The lists are tileList.txt at the top of the two AWS Open Data buckets the
terrain is read from:

    https://copernicus-dem-30m.s3.amazonaws.com/tileList.txt
    https://copernicus-dem-90m.s3.amazonaws.com/tileList.txt

Both were last modified 2022-05-09 when this was first run (2026-10-13):
26450 cells at 30 m, 26475 at 90 m. Run it again if Copernicus publishes
new lists - if it releases the 30 m tiles it now withholds, say.
"""

import base64
import os
import re
import sys
import zlib

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(
    __file__))), "copernicus_cells.py")
NAME = re.compile(
    r"^Copernicus_DSM_COG_(10|30)_([NS])(\d\d)_00_([EW])(\d\d\d)_00_DEM$")


def read(path, resolution):
    cells = set()
    for line in open(path, encoding="ascii"):
        line = line.strip()
        if not line:
            continue
        m = NAME.match(line)
        if not m or m.group(1) != resolution:
            raise SystemExit("%s: not a tile name of this set: %r"
                             % (path, line))
        lat = int(m.group(3)) * (1 if m.group(2) == "N" else -1)
        lon = int(m.group(5)) * (1 if m.group(4) == "E" else -1)
        if not (-90 <= lat <= 89 and -180 <= lon <= 179):
            raise SystemExit("%s: outside the world: %r" % (path, line))
        cells.add((lat, lon))
    return cells


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    c30 = read(sys.argv[1], "10")
    c90 = read(sys.argv[2], "30")
    if not c30 <= c90:
        raise SystemExit("cells at 30 m but not at 90 m: %s"
                         % sorted(c30 - c90))
    withheld = sorted(c90 - c30)
    bits = bytearray(180 * 360 // 8)
    for lat, lon in c90:
        i = (lat + 90) * 360 + (lon + 180)
        bits[i >> 3] |= 1 << (i & 7)
    blob = base64.b64encode(zlib.compress(bytes(bits), 9)).decode("ascii")
    lines = [blob[i:i + 72] for i in range(0, len(blob), 72)]
    rows = []
    for i in range(0, len(withheld), 6):
        rows.append("    " + " ".join("(%d, %d)," % c
                                      for c in withheld[i:i + 6]))
    text = '''"""Which one-degree cells Copernicus's elevation data covers, and how.

GENERATED by tools/make_copernicus_cells.py from Copernicus's own lists of
its tiles (tileList.txt in the copernicus-dem-30m and copernicus-dem-90m
buckets on AWS, last modified 2022-05-09) - not to be edited by hand.

kind() says, for the cell whose south-west corner is a whole degree:
  "30 m"  the 30 m set (GLO-30) has its tile - almost all land;
  "90 m"  only the 90 m set (GLO-90) has it. The Copernicus programme
          withholds its 30 m tiles of Armenia and Azerbaijan, and with them
          every cell they touch: in Turkey, Kars, Igdir and Cildir;
  "sea"   neither has it: open sea, where Copernicus says to take the
          height as 0 m. Inland water has tiles of its own, the Caspian's
          included.

Decided here, from the lists, rather than from what the tile store answers
when asked: a store that cannot be reached, or a network that answers "not
found" to everything (a hotel's sign-in page), must never turn land into
sea - 0 m under an aircraft following the terrain over a hill.
"""

import base64
import zlib

CELLS_30M = %d
CELLS_90M = %d

# Every cell the 90 m set has a tile for, as bits: (lat + 90) * 360 +
# (lon + 180), least significant first.
_LAND = zlib.decompress(base64.b64decode(
%s))

WITHHELD_30M = frozenset({
%s
})


def kind(lat_deg, lon_deg):
    """The kind of the cell at these whole degrees: "30 m", "90 m" or
    "sea"."""
    lat, lon = int(lat_deg), (int(lon_deg) + 180) %% 360 - 180
    if not -90 <= lat <= 89:
        return "sea"
    i = (lat + 90) * 360 + (lon + 180)
    if not _LAND[i >> 3] >> (i & 7) & 1:
        return "sea"
    return "90 m" if (lat, lon) in WITHHELD_30M else "30 m"
''' % (len(c30), len(c90),
       "\n".join('    "%s"' % line for line in lines), "\n".join(rows))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: %d cells at 30 m, %d at 90 m, %d withheld at 30 m: %s"
          % (OUT, len(c30), len(c90), len(withheld), withheld))


if __name__ == "__main__":
    main()
