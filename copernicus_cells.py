def kind(lat_deg, lon_deg):
    """The kind of the cell at these whole degrees: "30 m", "90 m" or
    "sea"."""
    lat, lon = int(lat_deg), (int(lon_deg) + 180) % 360 - 180
    if not -90 <= lat <= 89:
        return "sea"
    i = (lat + 90) * 360 + (lon + 180)
    if not _LAND[i >> 3] >> (i & 7) & 1:
        return "sea"
    return "90 m" if (lat, lon) in WITHHELD_30M else "30 m"
